const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createReviewStore } = require('../lib/review');
test('deduplicates, prioritizes, persists, schedules and rejects duplicate ratings', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'alexa-review-'));
  const file = path.join(dir, 'review.json');
  const store = createReviewStore(file);
  const phrase = { jp: '雨', romaji: 'ame', fr: 'pluie' };
  store.capture(phrase);
  store.capture(phrase, 'meaning', true);
  assert.equal(store.list().total, 1);
  const card = store.list().due[0];
  assert.equal(card.priority, true);
  const now = Date.now();
  assert.throws(() => store.rate(card.id, 'invalid', 0, now));
  const rated = store.rate(card.id, 'again', 0, now);
  assert.equal(rated.due, now + 60000);
  assert.equal(store.list(now).dueCount, 0);
  assert.throws(() => store.rate(card.id, 'good', 0, now + 60000));
  const restored = createReviewStore(file);
  assert.equal(restored.list(now + 60000).due[0].reviews, 1);
  const good = restored.rate(card.id, 'good', 1, now + 60000);
  assert.equal(good.interval, 3);
  const hard = restored.rate(card.id, 'hard', 2, good.due);
  assert.equal(hard.interval, 3.5999999999999996);
  const easy = restored.rate(card.id, 'easy', 3, hard.due);
  assert.ok(easy.interval > hard.interval);
  store.capture(phrase, 'question');
  assert.equal(store.list().total, 2);
});
